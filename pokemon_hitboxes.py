def get_height(numero, forme=None):
    """Retourne la hauteur réelle (m) d'un Pokémon selon sa forme.
    Fallback sur la forme de base si la forme n'est pas trouvée."""
    poke = POKEMON_HEIGHTS.get(numero)
    if not poke:
        return None
    if forme in poke:
        return poke[forme]
    if None in poke:
        return poke[None]
    return next(iter(poke.values()), None)
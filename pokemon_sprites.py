def get_sprite(numero, forme=None):
    """Retourne le nom du fichier sprite pour un Pokémon et sa forme.
    Fallback sur f00 si la forme n'est pas trouvée."""
    poke = POKEMON_SPRITES.get(numero)
    if not poke:
        return None
    # Essai exact
    if forme in poke:
        return poke[forme]
    # Essai None (forme de base)
    if None in poke:
        return poke[None]
    # Premier disponible
    return next(iter(poke.values()), None)